"""
GitHub Pull Request Creator
Creates pull requests on GitHub from generated code using the GitHub REST API.
"""

import requests
import base64
import re
import time
from datetime import datetime
from config import GITHUB_TOKEN


def _github_error(resp, action: str, owner: str, repo: str) -> str:
    """Explain a failed GitHub API call in terms the user can act on."""
    try:
        message = resp.json().get("message", "")
    except ValueError:
        message = resp.text[:200]
    status = resp.status_code
    if status == 401:
        return ("GitHub rejected the token (expired or revoked). Create a new one and "
                "update GITHUB_TOKEN on the backend or the token in Settings.")
    if status == 403 and "not accessible by personal access token" in message:
        return (f"Your GitHub token can't {action} in {owner}/{repo}. Give it Contents and "
                "Pull requests write access for this repository (fine-grained token), "
                "or use a classic token with the repo scope.")
    if status == 403 and "rate limit" in message.lower():
        return "GitHub's API rate limit was reached. Wait a few minutes and try again."
    if status in (403, 404) and action != "read the repository":
        return (f"You don't have write access to {owner}/{repo}. Connect a repository you "
                "own, or fork this one and connect the fork.")
    if status == 404:
        return (f"Repository {owner}/{repo} wasn't found, or your token can't see it "
                "(private repositories need the repo scope).")
    return f"Couldn't {action}: {message or status}"


def _ensure_fork(owner: str, repo: str, branch: str, headers: dict) -> dict:
    """Fork owner/repo into the token's account (or reuse an existing fork) and sync it."""
    resp = requests.post(f"https://api.github.com/repos/{owner}/{repo}/forks",
                         headers=headers, json={"default_branch_only": True}, timeout=30)
    if resp.status_code not in (200, 202):
        return {"error": _github_error(resp, "fork the repository", owner, repo)}
    fork = resp.json()
    fork_api = f"https://api.github.com/repos/{fork['full_name']}"

    # GitHub creates forks asynchronously; wait until the default branch exists
    for _ in range(30):
        if requests.get(f"{fork_api}/git/refs/heads/{branch}", headers=headers, timeout=15).ok:
            break
        time.sleep(2)
    else:
        return {"error": "GitHub is still creating the fork. Try again in a minute."}

    # An older fork may be behind upstream; best effort, a diverged fork still works
    requests.post(f"{fork_api}/merge-upstream", headers=headers, json={"branch": branch}, timeout=30)
    return {"api": fork_api, "owner": fork["owner"]["login"], "html_url": fork["html_url"]}


def create_pull_request(
    repo_url: str,
    files: list[dict],
    branch_name: str = None,
    commit_message: str = "Add code generated by ShipSafe",
    pr_title: str = "ShipSafe: Generated Code",
    pr_body: str = "",
    github_token: str = None,
) -> dict:
    """
    Create a GitHub pull request with the given files.

    Args:
        repo_url: GitHub repository URL
        files: List of dicts with 'path' and 'content' keys
        branch_name: Branch name (auto-generated if None)
        commit_message: Commit message
        pr_title: Pull request title
        pr_body: Pull request description
        github_token: GitHub token (falls back to env var)

    Returns:
        dict with 'pr_url', 'pr_number', 'branch' on success, or 'error'
    """
    token = github_token or GITHUB_TOKEN
    if not token or len(token) < 10:
        return {"error": "A valid GitHub token is required to create pull requests. Add one in Settings or set GITHUB_TOKEN on the backend."}

    # Parse owner/repo
    parts = repo_url.rstrip("/").removesuffix(".git").split("/")
    owner, repo = parts[-2], parts[-1]

    headers = {
        "Accept": "application/vnd.github.v3+json",
        "Authorization": f"token {token}",
    }
    api_base = f"https://api.github.com/repos/{owner}/{repo}"

    try:
        # Step 1: Get default branch and its latest commit SHA
        repo_resp = requests.get(api_base, headers=headers, timeout=15)
        if not repo_resp.ok:
            return {"error": _github_error(repo_resp, "read the repository", owner, repo)}
        repo_info = repo_resp.json()
        default_branch = repo_info.get("default_branch", "main")

        ref_resp = requests.get(
            f"{api_base}/git/refs/heads/{default_branch}",
            headers=headers, timeout=15,
        )
        if not ref_resp.ok:
            return {"error": _github_error(ref_resp, "read the default branch", owner, repo)}
        base_sha = ref_resp.json()["object"]["sha"]

        # Without push access, work in a fork and open the PR from there
        write_base, head_owner, fork_url = api_base, None, None
        if not repo_info.get("permissions", {}).get("push"):
            fork = _ensure_fork(owner, repo, default_branch, headers)
            if fork.get("error"):
                return fork
            write_base, head_owner, fork_url = fork["api"], fork["owner"], fork["html_url"]

        # Step 2: Create a new branch
        if not branch_name:
            timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            branch_name = f"shipsafe/{timestamp}"

        # Sanitize branch name
        branch_name = re.sub(r'[^a-zA-Z0-9/_-]', '-', branch_name)

        create_ref_resp = requests.post(
            f"{write_base}/git/refs",
            headers=headers,
            json={
                "ref": f"refs/heads/{branch_name}",
                "sha": base_sha,
            },
            timeout=15,
        )
        if create_ref_resp.status_code == 422 and fork_url and "already exists" not in create_ref_resp.text:
            # A diverged fork doesn't have upstream's latest commit; branch from the fork's own head
            fork_head = requests.get(f"{write_base}/git/refs/heads/{default_branch}", headers=headers, timeout=15)
            create_ref_resp = requests.post(
                f"{write_base}/git/refs", headers=headers, timeout=15,
                json={"ref": f"refs/heads/{branch_name}", "sha": fork_head.json()["object"]["sha"]},
            )
        if create_ref_resp.status_code == 422:
            # Branch already exists, get its SHA
            ref_resp2 = requests.get(
                f"{write_base}/git/refs/heads/{branch_name}",
                headers=headers, timeout=15,
            )
            if not ref_resp2.ok:
                return {"error": f"Branch '{branch_name}' already exists and could not be accessed."}
        elif not create_ref_resp.ok:
            return {"error": _github_error(create_ref_resp, "create a branch", owner, repo)}

        # Step 3: Create/update files on the new branch
        created_files = []
        for file_info in files:
            file_path = file_info.get("path", "").strip()
            file_content = file_info.get("content", "")

            if not file_path or not file_content:
                continue

            # Check if file exists (to get its SHA for update)
            existing_resp = requests.get(
                f"{write_base}/contents/{file_path}?ref={branch_name}",
                headers=headers, timeout=15,
            )
            file_sha = None
            if existing_resp.ok:
                file_sha = existing_resp.json().get("sha")

            # Create or update file
            payload = {
                "message": commit_message,
                "content": base64.b64encode(file_content.encode("utf-8")).decode("ascii"),
                "branch": branch_name,
            }
            if file_sha:
                payload["sha"] = file_sha

            put_resp = requests.put(
                f"{write_base}/contents/{file_path}",
                headers=headers,
                json=payload,
                timeout=15,
            )
            if put_resp.ok:
                created_files.append(file_path)
            else:
                return {"error": _github_error(put_resp, f"write {file_path}", owner, repo)}

        if not created_files:
            return {"error": "No files were committed. Make sure file paths and content are provided."}

        # Step 4: Create pull request
        if not pr_body:
            pr_body = (
                f"## 🤖 Generated by ShipSafe\n\n"
                f"This PR was auto-generated by ShipSafe's Code Generation Agent.\n\n"
                f"### Files\n" +
                "\n".join([f"- `{f}`" for f in created_files]) +
                f"\n\n---\n*Created with [ShipSafe](https://github.com) AI Codebase Assistant*"
            )

        pr_resp = requests.post(
            f"{api_base}/pulls",
            headers=headers,
            json={
                "title": pr_title,
                "body": pr_body,
                "head": f"{head_owner}:{branch_name}" if head_owner else branch_name,
                "base": default_branch,
            },
            timeout=15,
        )

        if not pr_resp.ok:
            error_msg = pr_resp.json().get("message", pr_resp.text)
            # If PR already exists for this branch
            if "A pull request already exists" in error_msg:
                return {
                    "pr_url": f"https://github.com/{owner}/{repo}/compare/{branch_name}",
                    "branch": branch_name,
                    "files_committed": created_files,
                    "message": f"Files committed to '{branch_name}'. A PR already exists for this branch.",
                }
            return {"error": _github_error(pr_resp, "open a pull request", owner, repo)}

        pr_data = pr_resp.json()
        return {
            "pr_url": pr_data.get("html_url", ""),
            "pr_number": pr_data.get("number"),
            "branch": branch_name,
            "files_committed": created_files,
            "fork_url": fork_url,
            "message": f"Pull request #{pr_data.get('number')} created successfully!"
                       + (" (from your fork)" if fork_url else ""),
        }

    except requests.exceptions.RequestException as e:
        return {"error": f"GitHub API error: {str(e)}"}
    except Exception as e:
        return {"error": f"Unexpected error: {str(e)}"}
