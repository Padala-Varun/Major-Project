import React, { useState } from 'react';
import { ExternalLink, GitPullRequest, LoaderCircle, TriangleAlert } from 'lucide-react';
import { createPullRequest } from '../services/api';
import { BRAND } from '../brand';
import { Modal } from './ui';

const EXTENSIONS = {
  python: 'py', py: 'py', javascript: 'js', js: 'js', jsx: 'jsx', typescript: 'ts', ts: 'ts',
  tsx: 'tsx', java: 'java', go: 'go', rust: 'rs', ruby: 'rb', php: 'php', csharp: 'cs',
  cpp: 'cpp', c: 'c', kotlin: 'kt', swift: 'swift', html: 'html', css: 'css', json: 'json',
  yaml: 'yml', yml: 'yml', bash: 'sh', sh: 'sh', sql: 'sql', markdown: 'md',
};
const COMMAND_LANGUAGES = new Set(['bash', 'sh', 'shell', 'console', 'powershell', 'cmd', 'text']);
const VERDICT_LINES = {
  pass: '✅ Verified in a sandbox',
  fail: '❌ Sandbox tests failed',
  no_tests: 'ℹ️ No test suite to run (files compile)',
  error: "⚠️ Sandbox verification didn't complete",
};

/** Files for the dialog from raw code blocks, when changes weren't prepared. */
export function filesFromBlocks(codeBlocks) {
  // When the Engineer named its files, unnamed blocks are usually usage examples
  const anyNamed = codeBlocks.some((b) => b.filename);
  return codeBlocks.map((b, i) => ({
    path: b.filename || `generated/file_${i + 1}.${EXTENSIONS[b.language] || 'txt'}`,
    content: b.code || '',
    language: b.language || 'text',
    status: 'new',
    include: b.filename ? true : !anyNamed && !COMMAND_LANGUAGES.has((b.language || '').toLowerCase()),
  }));
}

function prBody({ title, issue, impact, critic, verification, files }) {
  const lines = [`## ${issue ? `Fix #${issue.number}: ${issue.title}` : title || 'Generated changes'}`, ''];
  if (issue) lines.push(`Closes #${issue.number}`, '');
  if (verification?.verdict) lines.push(`**${VERDICT_LINES[verification.verdict]}:** ${verification.summary}`, '');
  if (critic?.approved != null) {
    lines.push(`**Critic review:** ${critic.approved ? '✅ approved' : '⚠️ changes requested'}`
      + `${critic.score != null ? ` (${critic.score}/10)` : ''}`, '');
  }
  if (impact) {
    lines.push(`### Impact analysis: ${impact.level.toUpperCase()}`, '', impact.summary, '');
    impact.reasons.forEach((r) => lines.push(`- ${r}`));
    const direct = impact.affected.filter((a) => a.depth === 1).map((a) => `\`${a.path}\``);
    if (direct.length) lines.push('', `**Directly affected:** ${direct.slice(0, 15).join(', ')}`);
    lines.push('');
  }
  lines.push('### Files');
  files.forEach((f) => lines.push(`- \`${f.path}\`${f.additions != null ? ` (+${f.additions} −${f.deletions})` : ''}`));
  lines.push('', '---', `*Generated by ${BRAND.name}'s agent team.*`);
  return lines.join('\n');
}

export default function CreatePRModal({
  files: initialFiles, repoUrl, githubToken, title, issue, impact, critic, verification, onClose,
}) {
  const [files, setFiles] = useState(() => initialFiles.map((f) => ({ include: true, ...f })));
  const [branch, setBranch] = useState('');
  const [prTitle, setPrTitle] = useState(() => (issue
    ? `Fix #${issue.number}: ${issue.title}`
    : `${BRAND.name}: ${title || 'generated changes'}`).slice(0, 100));
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [result, setResult] = useState(null);

  const update = (i, patch) => setFiles((prev) => prev.map((x, j) => (j === i ? { ...x, ...patch } : x)));

  const submit = async () => {
    const valid = files.filter((f) => f.include && f.path.trim() && f.content.trim());
    if (!repoUrl) return setError('No repository connected.');
    if (!valid.length) return setError('Select at least one file to commit.');

    setLoading(true);
    setError(null);
    try {
      setResult(await createPullRequest({
        repoUrl,
        githubToken: githubToken || null,
        files: valid.map(({ path, content }) => ({ path: path.trim(), content })),
        branchName: branch.trim() || null,
        commitMessage: prTitle,
        prTitle,
        prBody: prBody({ title, issue, impact, critic, verification, files: valid }),
      }));
    } catch (err) {
      setError(err.response?.data?.detail || err.message || 'Failed to create the pull request.');
    } finally {
      setLoading(false);
    }
  };

  const icon = <GitPullRequest size={18} className="muted" />;

  if (result) {
    return (
      <Modal title="Pull request opened" icon={icon} onClose={onClose}
        footer={<button className="btn btn-outline" onClick={onClose}>Done</button>}>
        <div className="pr-success">
          <div className="pr-success-icon"><GitPullRequest size={20} /></div>
          <h4>{result.message || 'Pull request created'}</h4>
          <p>
            {result.files_committed?.length || files.length} file(s) committed to <code>{result.branch}</code>
            {result.fork_url && <> on your fork</>}
          </p>
          {result.pr_url && (
            <a className="btn btn-primary" href={result.pr_url} target="_blank" rel="noopener noreferrer">
              View on GitHub <ExternalLink size={14} />
            </a>
          )}
        </div>
      </Modal>
    );
  }

  return (
    <Modal
      title="Open a pull request"
      subtitle={issue ? `Fixes #${issue.number} · commits to a new branch` : 'Commit the changes to a new branch'}
      icon={icon}
      onClose={onClose}
      footer={(
        <>
          <button className="btn btn-ghost" onClick={onClose} disabled={loading}>Cancel</button>
          <button className="btn btn-primary" onClick={submit} disabled={loading}>
            {loading ? <LoaderCircle size={14} className="spin" /> : <GitPullRequest size={14} />}
            {loading ? 'Opening…' : 'Open pull request'}
          </button>
        </>
      )}
    >
      {verification?.verdict && (
        <div className={`callout ${verification.verdict === 'pass' ? 'success' : verification.verdict === 'no_tests' ? '' : 'danger'}`}
          style={{ marginBottom: 14 }}>
          <span>{VERDICT_LINES[verification.verdict]}: {verification.summary}</span>
        </div>
      )}
      <div className="field">
        <label>Files</label>
        {files.map((f, i) => (
          <div className={`file-row ${f.include ? '' : 'excluded'}`} key={i}>
            <input
              type="checkbox"
              className="file-check"
              checked={f.include}
              onChange={(e) => update(i, { include: e.target.checked })}
              aria-label={`Commit ${f.path}`}
            />
            <input
              className="input mono"
              value={f.path}
              onChange={(e) => update(i, { path: e.target.value })}
              placeholder="path/in/repo.py"
              disabled={!f.include || f.status !== 'new'}
              title={f.status !== 'new' ? 'Existing file: the path is fixed' : undefined}
            />
            <span className="lang">
              {f.additions != null ? <><span className="add">+{f.additions}</span> <span className="del">−{f.deletions}</span></> : f.language}
            </span>
          </div>
        ))}
        <span className="field-hint">
          {files.some((f) => f.status === 'new' && f.additions == null)
            ? "Paths come from the Engineer's output. Unchecked blocks (usage examples, commands) aren't committed."
            : 'Complete files, with partial changes already merged into the existing code.'}
        </span>
      </div>
      <div className="field">
        <label htmlFor="pr-title">Title</label>
        <input id="pr-title" className="input" value={prTitle} onChange={(e) => setPrTitle(e.target.value)} />
      </div>
      <div className="field">
        <label htmlFor="pr-branch">Branch</label>
        <input id="pr-branch" className="input mono" value={branch} onChange={(e) => setBranch(e.target.value)}
          placeholder="Auto-generated if empty" />
        <span className="field-hint">No write access to this repository? It's forked to your account automatically.</span>
      </div>
      {error && (
        <div className="callout danger" style={{ marginBottom: 14 }}>
          <TriangleAlert size={15} /><span>{error}</span>
        </div>
      )}
    </Modal>
  );
}
